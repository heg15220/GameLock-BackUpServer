import { chromium } from 'playwright';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const base = process.argv[2] || 'http://127.0.0.1:5193';
const output = process.argv[3] || 'output/manager-v9/browser-archive';
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const checks = [], errors = [], consoleErrors = [];
try {
  for (const [name, viewport] of [['desktop', { width: 1440, height: 1000 }], ['mobile', { width: 390, height: 844 }]]) {
    const page = await browser.newPage({ viewport, reducedMotion: 'reduce' });
    page.setDefaultTimeout(30000);
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error') consoleErrors.push(message.text()); });
    await page.goto(`${base}/es/games/sports-manager?archive=v10`, { waitUntil: 'networkidle' });
    const cookie = page.locator('.cookie-consent-primary');
    if (await cookie.isVisible()) await cookie.click();
    await page.getByLabel('Temporada inicial').selectOption('2017');
    await page.getByRole('button', { name: 'Datos y cobertura', exact: true }).click();
    const panel = page.getByTestId('archive-coverage');
    await panel.waitFor();
    assert.equal(await panel.getByLabel('Liga del archivo').locator('option').count(), 51);
    assert.equal(await panel.getByLabel('Año del archivo').locator('option').count(), 36);
    assert.match(await panel.innerText(), /20\/20/);
    await panel.getByLabel('Año del archivo').selectOption('1990');
    await panel.getByLabel('Liga del archivo').selectOption('liga-dominicana-de-futbol');
    assert.match(await panel.innerText(), /Sin lista verificada/);
    await panel.getByLabel('Año del archivo').selectOption('2013');
    await panel.getByLabel('Liga del archivo').selectOption('laliga');
    assert.match(await panel.innerText(), /2013-09-02/);
    const sources = await panel.locator('.fm-archive-summary a').evaluateAll(nodes => nodes.map(n => n.href));
    assert.ok(sources.length >= 2 && sources.every(url => url.startsWith('https://')));
    await panel.getByLabel('Año del archivo').selectOption('2009');
    await panel.getByLabel('Liga del archivo').selectOption('ligue-1');
    assert.match(await panel.innerText(), /2009-06-09.*2009-08-31/);
    assert.match(await panel.innerText(), /2010-01-04.*2010-02-01/);
    await panel.getByLabel('Año del archivo').selectOption('2014');
    await panel.getByLabel('Liga del archivo').selectOption('laliga');
    assert.match(await panel.innerText(), /2\/2 con fechas completas documentadas/);
    assert.ok(await panel.locator('a[href*="web.archive.org"]').count() > 0);
    await panel.getByLabel('Año del archivo').selectOption('2018');
    await panel.getByLabel('Liga del archivo').selectOption('championship');
    assert.match(await panel.innerText(), /2018-08-09/);
    await panel.scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${output}/${name}-coverage.png` });
    const layout = await page.evaluate(() => ({ viewport: innerWidth, page: document.documentElement.scrollWidth,
      game: document.querySelector('.fm-game').clientWidth, scroll: document.querySelector('.fm-game').scrollWidth }));
    assert.ok(layout.page <= layout.viewport + 1 && layout.scroll <= layout.game + 1, `${name} no overflow`);
    checks.push(`${name}:51 leagues,36 years, unavailable season, date evidence and responsive layout`);
    await page.getByRole('button', { name: 'Datos y cobertura', exact: true }).click();
    await page.getByLabel('Liga', { exact: true }).selectOption('laliga');
    await page.getByLabel('Tu club', { exact: true }).selectOption('sd-eibar');
    await page.getByRole('button', { name: 'Firmar y empezar', exact: true }).click();
    await page.getByRole('navigation', { name: 'Secciones del mánager' }).getByRole('button', { name: 'Plantilla', exact: true }).click();
    const provenance = page.locator('.fm-player-provenance').filter({ hasText: 'Pappalardo' }).first();
    await provenance.locator('summary').click();
    await provenance.scrollIntoViewIfNeeded();
    assert.match(await provenance.innerText(), /CC BY 4.0/);
    assert.match(await provenance.innerText(), /2017-09-01/);
    assert.match(await provenance.innerText(), /No acredita inscripción continua/);
    await page.screenshot({ path: `${output}/${name}-provenance.png` });
    await fs.writeFile(`${output}/${name}.state.json`, await page.evaluate(() => window.render_game_to_text()));
    checks.push(`${name}:2017 Eibar career has research player provenance, attribution and cutoff`);
    await page.getByRole('navigation', { name: 'Secciones del mánager' }).getByRole('button', { name: 'Despacho', exact: true }).click();
    await page.getByRole('button', { name: 'Simulación rápida', exact: true }).click();
    await page.waitForFunction(() => JSON.parse(window.render_game_to_text()).round > 0);
    const afterMatch = JSON.parse(await page.evaluate(() => window.render_game_to_text()));
    assert.ok(afterMatch.round > 0);
    await fs.writeFile(`${output}/${name}-played.state.json`, JSON.stringify(afterMatch, null, 2));
    checks.push(`${name}:new historical squad completes a simulated match`);
    await page.close();
  }
  assert.deepEqual(errors, []); assert.deepEqual(consoleErrors, []);
  const report = { checks, errors, consoleErrors };
  await fs.writeFile(`${output}/verification.json`, JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} finally { await browser.close(); }
